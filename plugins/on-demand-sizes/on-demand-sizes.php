<?php
/*
Plugin Name: On demand sizes
Description: Deletes all generated derivatives in uploads and regenerates missing -WxH files on request. Auto-updates .htaccess on Apache.
Version: 1.0.1
Author: https://prospettiva.digital
*/

defined('ABSPATH') || exit;

class OD_Uploads_On_Demand {
  const SLUG = 'od-uploads-ondemand';
  const NONCE = 'od_uod_nonce';
  const HT_START = '# BEGIN OD_UPLOADS_ONDEMAND';
  const HT_END = '# END OD_UPLOADS_ONDEMAND';

  public static function init() {
    add_action('init', [__CLASS__,'register_query_vars']);
    add_action('template_redirect', [__CLASS__,'handle_on_demand'], 0);

    add_action('admin_menu', [__CLASS__,'admin_menu']);
    add_action('admin_post_od_uod_cleanup', [__CLASS__,'handle_cleanup']);
    add_action('admin_post_od_uod_htaccess', [__CLASS__,'handle_htaccess']);

    register_activation_hook(__FILE__, [__CLASS__,'on_activate']);
    register_deactivation_hook(__FILE__, [__CLASS__,'on_deactivate']);
  }

  public static function register_query_vars() {
    add_filter('query_vars', function($vars){
      $vars[] = 'od_uod';
      $vars[] = 'od_uod_rel';
      $vars[] = 'od_uod_w';
      $vars[] = 'od_uod_h';
      $vars[] = 'od_uod_ext';
      return $vars;
    });
  }

  public static function on_activate() {
    if(self::is_apache()){
      self::ensure_htaccess_rules(true);
    }
  }

  public static function on_deactivate() {
    if(self::is_apache()){
      self::ensure_htaccess_rules(false);
    }
  }

  private static function is_apache() {
    $sw = isset($_SERVER['SERVER_SOFTWARE']) ? strtolower((string)$_SERVER['SERVER_SOFTWARE']) : '';
    if($sw && strpos($sw,'apache') !== false){
      return true;
    }
    if(function_exists('apache_get_version')){
      return true;
    }
    return false;
  }

  private static function htaccess_path() {
    if(function_exists('get_home_path')){
      return rtrim(get_home_path(),'/').'/.htaccess';
    }
    return rtrim(ABSPATH,'/').'/.htaccess';
  }

  private static function uploads_rel_path_for_htaccess() {
    $u = wp_get_upload_dir();
    $baseurl = isset($u['baseurl']) ? (string)$u['baseurl'] : '';
    $site = site_url('/');
    $site_path = parse_url($site, PHP_URL_PATH);
    $up_path = parse_url($baseurl, PHP_URL_PATH);

    if($up_path === null){
      return 'wp-content/uploads';
    }

    $site_path = $site_path ? rtrim($site_path,'/') : '';
    $up_path = ltrim((string)$up_path,'/');

    if($site_path){
      $site_path_norm = ltrim($site_path,'/');
      if(strpos($up_path, $site_path_norm.'/') === 0){
        $up_path = substr($up_path, strlen($site_path_norm)+1);
      }
    }

    $up_path = trim($up_path,'/');
    return $up_path ? $up_path : 'wp-content/uploads';
  }

  private static function htaccess_lines() {
    $uploads_rel = self::uploads_rel_path_for_htaccess();
    return [
      self::HT_START,
      '<IfModule mod_rewrite.c>',
      'RewriteEngine On',
      'RewriteCond %{REQUEST_FILENAME} !-f',
      'RewriteCond %{REQUEST_FILENAME} !-d',
      'RewriteRule ^'.str_replace('/','\/',$uploads_rel).'/(.+)-([0-9]{1,5})x([0-9]{1,5})\.(jpe?g|png|gif|webp|avif)$ index.php?od_uod=1&od_uod_rel=$1&od_uod_w=$2&od_uod_h=$3&od_uod_ext=$4 [L,QSA,NC]',
      '</IfModule>',
      self::HT_END
    ];
  }

  private static function strip_od_block($content) {
    $pattern = '~'.preg_quote(self::HT_START,'~').'.*?'.preg_quote(self::HT_END,'~').'\s*~s';
    return preg_replace($pattern, '', (string)$content, 1);
  }

  private static function ensure_htaccess_rules($enable) {
    $path = self::htaccess_path();

    if(!file_exists($path)){
      if(!$enable){
        return ['ok'=>true,'msg'=>'.htaccess not found, nothing to remove'];
      }
      $dir = dirname($path);
      if(!is_dir($dir) || !is_writable($dir)){
        return ['ok'=>false,'msg'=>'Cannot create .htaccess (directory not writable): '.$dir];
      }
      file_put_contents($path, "# Generated by WordPress\n");
    }

    if(!is_writable($path)){
      return ['ok'=>false,'msg'=>'htaccess not writable: '.$path];
    }

    $content = (string)file_get_contents($path);
    $content = self::strip_od_block($content);

    if(!$enable){
      file_put_contents($path, trim($content)."\n");
      return ['ok'=>true,'msg'=>'Rules removed from .htaccess'];
    }

    $lines = self::htaccess_lines();
    $block = implode("\n", $lines)."\n";

    /* Il blocco va PRIMA di "# BEGIN WordPress", mai dentro: inserito prima
       di "RewriteRule . /index.php [L]" separava quella regola dalle sue
       RewriteCond, e ogni richiesta (anche wp-login.php) finiva su index.php
       con un redirect infinito. Fuori dai marcatori WordPress non lo riscrive. */
    $begin = strpos($content, '# BEGIN WordPress');

    if($begin === false){
      $content = rtrim($content)."\n\n".$block;
      file_put_contents($path, $content);
      return ['ok'=>true,'msg'=>'Rules added (WordPress markers not found)'];
    }

    $content = substr($content, 0, $begin).$block.substr($content, $begin);
    file_put_contents($path, $content);

    return ['ok'=>true,'msg'=>'Rules added before the WordPress block'];
  }

  public static function admin_menu() {
    add_management_page('OD Uploads On-Demand','OD Uploads On-Demand','manage_options',self::SLUG,[__CLASS__,'render_page']);
  }

  public static function render_page() {
    if(!current_user_can('manage_options')){
      wp_die('Forbidden');
    }

    $uploads = wp_get_upload_dir();
    $basedir = isset($uploads['basedir']) ? (string)$uploads['basedir'] : '';
    $baseurl = isset($uploads['baseurl']) ? (string)$uploads['baseurl'] : '';

    $done = isset($_GET['od_msg']) ? sanitize_text_field((string)$_GET['od_msg']) : '';

    print '<div class="wrap">';
    print '<h1>OD Uploads On-Demand</h1>';

    if($done !== ''){
      print '<div class="notice notice-success"><p>'.esc_html($done).'</p></div>';
    }

    print '<p><strong>Uploads</strong><br>Basedir: '.esc_html($basedir).'<br>Baseurl: '.esc_html($baseurl).'</p>';

    print '<hr>';
    print '<h2>Cleanup</h2>';
    print '<form method="post" action="'.esc_url(admin_url('admin-post.php')).'">';
    print '<input type="hidden" name="action" value="od_uod_cleanup">';
    print '<input type="hidden" name="'.esc_attr(self::NONCE).'" value="'.esc_attr(wp_create_nonce(self::NONCE)).'">';
    print '<p><label><input type="checkbox" name="delete_wxh" value="1" checked> Delete all <code>-WxH</code> derivatives (also @2x)</label></p>';
    print '<p><label><input type="checkbox" name="delete_scaled" value="1" checked> Delete <code>*-scaled.*</code></label></p>';
    print '<p><label><input type="checkbox" name="only_if_original" value="1" checked> Delete only if an original exists</label></p>';
    print '<p><label><input type="checkbox" name="dry_run" value="1"> Dry run (no delete)</label></p>';
    print '<p><button class="button button-primary" type="submit">Run cleanup</button></p>';
    print '</form>';

    print '<hr>';
    print '<h2>Server integration</h2>';

    if(self::is_apache()){
      $ht = self::htaccess_path();
      print '<p><strong>Detected:</strong> Apache</p>';
      print '<p><strong>.htaccess:</strong> '.esc_html($ht).'</p>';

      print '<form method="post" action="'.esc_url(admin_url('admin-post.php')).'">';
      print '<input type="hidden" name="action" value="od_uod_htaccess">';
      print '<input type="hidden" name="'.esc_attr(self::NONCE).'" value="'.esc_attr(wp_create_nonce(self::NONCE)).'">';
      print '<p><button class="button" type="submit" name="mode" value="add">Add/Repair .htaccess rules</button> ';
      print '<button class="button" type="submit" name="mode" value="remove">Remove .htaccess rules</button></p>';
      print '</form>';
    } else {
      print '<p><strong>Detected:</strong> Non-Apache (likely Nginx/LiteSpeed/Proxy)</p>';
      print '<p><strong>Nginx snippet</strong> (add in your server block):</p>';
      print '<pre style="background:#fff;border:1px solid #ccd0d4;padding:12px;max-width:100%;overflow:auto;">location ~* /uploads/.+-(\\d{1,5})x(\\d{1,5})\\.(jpe?g|png|gif|webp|avif)$ {\n  try_files $uri /index.php?$args;\n}\n</pre>';
    }

    print '</div>';
  }

  public static function handle_htaccess() {
    if(!current_user_can('manage_options')){
      wp_die('Forbidden');
    }
    if(!isset($_POST[self::NONCE]) || !wp_verify_nonce((string)$_POST[self::NONCE], self::NONCE)){
      wp_die('Bad nonce');
    }

    $mode = isset($_POST['mode']) ? (string)$_POST['mode'] : 'add';

    if(!self::is_apache()){
      wp_safe_redirect(add_query_arg(['page'=>self::SLUG,'od_msg'=>rawurlencode('Not Apache: cannot manage .htaccess here')], admin_url('tools.php')));
      exit;
    }

    $res = self::ensure_htaccess_rules($mode === 'add');
    $msg = $res['ok'] ? $res['msg'] : ('ERROR: '.$res['msg']);

    wp_safe_redirect(add_query_arg(['page'=>self::SLUG,'od_msg'=>rawurlencode($msg)], admin_url('tools.php')));
    exit;
  }

  public static function handle_cleanup() {
    if(!current_user_can('manage_options')){
      wp_die('Forbidden');
    }
    if(!isset($_POST[self::NONCE]) || !wp_verify_nonce((string)$_POST[self::NONCE], self::NONCE)){
      wp_die('Bad nonce');
    }

    $delete_wxh = isset($_POST['delete_wxh']) && $_POST['delete_wxh'] === '1';
    $delete_scaled = isset($_POST['delete_scaled']) && $_POST['delete_scaled'] === '1';
    $only_if_original = !isset($_POST['only_if_original']) || $_POST['only_if_original'] === '1';
    $dry_run = isset($_POST['dry_run']) && $_POST['dry_run'] === '1';

    $uploads = wp_get_upload_dir();
    $basedir = rtrim((string)$uploads['basedir'],'/');

    $exts = ['jpg','jpeg','png','gif','webp','avif'];

    $it = new RecursiveIteratorIterator(
      new RecursiveDirectoryIterator($basedir, FilesystemIterator::SKIP_DOTS),
      RecursiveIteratorIterator::SELF_FIRST
    );

    $matched = 0;
    $deleted = 0;

    foreach($it as $f){
      if(!$f->isFile()){
        continue;
      }

      $name = $f->getFilename();
      $path = $f->getPathname();

      $base_candidate = null;
      $is_match = false;

      if($delete_wxh && preg_match('~^(.*)-(\d{1,5})x(\d{1,5})(@\d+x)?\.(jpe?g|png|gif|webp|avif)$~i',$name,$m)){
        $is_match = true;
        $base_candidate = $m[1];
      }

      if(!$is_match && $delete_scaled && preg_match('~^(.*)-scaled\.(jpe?g|png|gif|webp|avif)$~i',$name,$m2)){
        $is_match = true;
        $base_candidate = $m2[1];
      }

      if(!$is_match){
        continue;
      }

      $matched++;

      if($only_if_original && $base_candidate){
        $dir = $f->getPath();
        $has_original = false;

        foreach($exts as $e){
          $orig = $dir.'/'.$base_candidate.'.'.$e;
          if(file_exists($orig)){
            $has_original = true;
            break;
          }
        }

        if(!$has_original){
          continue;
        }
      }

      if($dry_run){
        continue;
      }

      if(@unlink($path)){
        $deleted++;
      }
    }

    $msg = $dry_run
      ? 'Dry run: matched '.$matched.' files (no deletions).'
      : 'Done: matched '.$matched.' files, deleted '.$deleted.'.';

    wp_safe_redirect(add_query_arg(['page'=>self::SLUG,'od_msg'=>rawurlencode($msg)], admin_url('tools.php')));
    exit;
  }

  public static function handle_on_demand() {
    $q = get_query_var('od_uod');
    if($q !== '1'){
      return;
    }

    if(defined('OD_UOD_RUNNING') && OD_UOD_RUNNING){
      self::status_exit(500);
    }
    define('OD_UOD_RUNNING', true);

    $rel = (string)get_query_var('od_uod_rel');
    $w = (int)get_query_var('od_uod_w');
    $h = (int)get_query_var('od_uod_h');
    $ext = strtolower((string)get_query_var('od_uod_ext'));

    if($w < 1 || $h < 1 || $w > 6000 || $h > 6000){
      self::status_exit(400);
    }

    if($rel === '' || strpos($rel,'..') !== false){
      self::status_exit(400);
    }

    if(!preg_match('~^[a-z0-9/_\.-]+$~i',$rel)){
      self::status_exit(400);
    }

    if(!in_array($ext, ['jpg','jpeg','png','gif','webp','avif'], true)){
      self::status_exit(400);
    }

    $uploads = wp_get_upload_dir();
    $basedir = rtrim((string)$uploads['basedir'],'/');

    $dest = $basedir.'/'.$rel.'-'.$w.'x'.$h.'.'.$ext;
    if(file_exists($dest)){
      self::serve_file($dest);
    }

    $orig = null;
    $candidates = [];

    $candidates[] = $basedir.'/'.$rel.'.'.$ext;
    foreach(['jpg','jpeg','png','gif','webp','avif'] as $e){
      $p = $basedir.'/'.$rel.'.'.$e;
      if($p !== $candidates[0]){
        $candidates[] = $p;
      }
    }

    foreach($candidates as $p){
      if(file_exists($p)){
        $orig = $p;
        break;
      }
    }

    if(!$orig){
      self::status_exit(404);
    }

    $dir = dirname($dest);
    if(!is_dir($dir)){
      if(!wp_mkdir_p($dir)){
        self::status_exit(500);
      }
    }

    $filter_sizes = function($sizes){
      return [];
    };

    add_filter('intermediate_image_sizes_advanced', $filter_sizes, 9999);

    $editor = wp_get_image_editor($orig);
    if(is_wp_error($editor)){
      remove_filter('intermediate_image_sizes_advanced', $filter_sizes, 9999);
      self::status_exit(500);
    }

    $res = $editor->resize($w, $h, true);
    if(is_wp_error($res)){
      remove_filter('intermediate_image_sizes_advanced', $filter_sizes, 9999);
      self::status_exit(500);
    }

    $mime = self::mime_for_ext($ext);
    $saved = $editor->save($dest, $mime);

    remove_filter('intermediate_image_sizes_advanced', $filter_sizes, 9999);

    if(is_wp_error($saved)){
      self::status_exit(500);
    }

    self::serve_file($dest);
  }

  private static function status_exit($code) {
    if(!headers_sent()){
      status_header((int)$code);
    }
    exit;
  }

  private static function mime_for_ext($ext) {
    if($ext === 'jpg' || $ext === 'jpeg') return 'image/jpeg';
    if($ext === 'png') return 'image/png';
    if($ext === 'gif') return 'image/gif';
    if($ext === 'webp') return 'image/webp';
    if($ext === 'avif') return 'image/avif';
    return 'application/octet-stream';
  }

  private static function serve_file($path) {
    if(!is_file($path) || !is_readable($path)){
      self::status_exit(404);
    }

    $ext = strtolower(pathinfo($path, PATHINFO_EXTENSION));
    $mime = self::mime_for_ext($ext);

    if(!headers_sent()){
      status_header(200);
      header('Content-Type: '.$mime);
      header('Content-Length: '.(string)filesize($path));
      header('Cache-Control: public, max-age=31536000, immutable');
    }

    readfile($path);
    exit;
  }
}

OD_Uploads_On_Demand::init();